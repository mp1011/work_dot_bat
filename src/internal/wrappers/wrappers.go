// Package wrappers writes `.tools/<tool>` launchers into a project repo so a developer can start
// work, auto_daemon or prepare_for_push from the repo itself. The wrappers embed local absolute
// paths, so the directory ignores itself (a `*` .gitignore) and is never committed.
package wrappers

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Dir is the wrapper directory inside a project repo.
const Dir = ".tools"

// Tools are the launchers that get a wrapper.
var Tools = []string{"work", "auto_daemon", "prepare_for_push"}

// Install (re)writes the wrappers for project into repoPath/.tools, pointing at toolRoot/.tools.
// It returns the files written. The repo directory must already exist.
func Install(repoPath, toolRoot, project string) ([]string, error) {
	if filepath.Clean(repoPath) == filepath.Clean(toolRoot) {
		return nil, nil
	}
	if st, err := os.Stat(repoPath); err != nil || !st.IsDir() {
		return nil, fmt.Errorf("repo %s is not a directory", repoPath)
	}
	dir := filepath.Join(repoPath, Dir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	posixRoot := strings.ReplaceAll(toolRoot, `\`, "/")
	winRoot := strings.ReplaceAll(toolRoot, "/", `\`)
	var written []string
	write := func(name, content string, mode os.FileMode) error {
		path := filepath.Join(dir, name)
		if err := os.WriteFile(path, []byte(content), mode); err != nil {
			return err
		}
		written = append(written, path)
		return nil
	}
	if err := write(".gitignore", "*\n", 0o644); err != nil {
		return nil, err
	}
	for _, tool := range Tools {
		sh := fmt.Sprintf("#!/usr/bin/env bash\n# Generated by work_dot_bat; local paths, not committed.\ncd \"%s\" && exec \"%s/.tools/%s\" project=%s \"$@\"\n", posixRoot, posixRoot, tool, project)
		bat := fmt.Sprintf("@echo off\r\nrem Generated by work_dot_bat; local paths, not committed.\r\ncd /d \"%s\" && call \"%s\\.tools\\%s.bat\" project=%s %%*\r\nexit /b %%errorlevel%%\r\n", winRoot, winRoot, tool, project)
		if err := write(tool, sh, 0o755); err != nil {
			return nil, err
		}
		if err := write(tool+".bat", bat, 0o755); err != nil {
			return nil, err
		}
	}
	return written, nil
}
